function iniciarGaleria() {

    const boton =
        document.getElementById(
            "verMasFotos"
        );

    const galeria =
        document.getElementById(
            "galeriaExperiencia"
        );

    const visor =
        document.getElementById(
            "visorFotos"
        );

    const imagenVisor =
        document.getElementById(
            "imagenVisor"
        );

    const cerrar =
        document.getElementById(
            "cerrarVisor"
        );

    if (
        boton &&
        galeria
    ) {

        boton.addEventListener(
            "click",
            () => {

                galeria.classList.toggle(
                    "mostrar"
                );

                if (
                    galeria.classList.contains(
                        "mostrar"
                    )
                ) {

                    boton.textContent =
                        "📷 OCULTAR FOTOS";

                    setTimeout(
                        () => {

                            galeria.scrollIntoView({
                                behavior: "smooth",
                                block: "start"
                            });

                        },
                        100
                    );

                } else {

                    boton.textContent =
                        "📸 VER MÁS FOTOS";

                }

            }
        );

    }

    document
        .querySelectorAll(
            ".foto-experiencia"
        )
        .forEach(
            foto => {

                foto.addEventListener(
                    "click",
                    () => {

                        if (
                            !visor ||
                            !imagenVisor
                        ) {
                            return;
                        }

                        imagenVisor.src =
                            foto.dataset.foto;

                        visor.classList.add(
                            "abierto"
                        );

                    }
                );

            }
        );

    if (
        cerrar &&
        visor
    ) {

        cerrar.addEventListener(
            "click",
            () => {

                visor.classList.remove(
                    "abierto"
                );

            }
        );

    }

    if (visor) {

        visor.addEventListener(
            "click",
            evento => {

                if (
                    evento.target === visor
                ) {

                    visor.classList.remove(
                        "abierto"
                    );

                }

            }
        );

    }

    document.addEventListener(
        "keydown",
        evento => {

            if (
                evento.key === "Escape" &&
                visor
            ) {

                visor.classList.remove(
                    "abierto"
                );

            }

        }
    );

    const elementos3D =
        document.querySelectorAll(
            ".experiencia-imagen-contenedor, .foto-experiencia"
        );

    elementos3D.forEach(
        elemento => {

            elemento.addEventListener(
                "mousemove",
                evento => {

                    if (
                        window.innerWidth < 800
                    ) {
                        return;
                    }

                    const rect =
                        elemento.getBoundingClientRect();

                    const x =
                        evento.clientX -
                        rect.left;

                    const y =
                        evento.clientY -
                        rect.top;

                    const centroX =
                        rect.width / 2;

                    const centroY =
                        rect.height / 2;

                    const rotacionY =
                        (
                            (x - centroX) /
                            centroX
                        ) * 9;

                    const rotacionX =
                        -(
                            (y - centroY) /
                            centroY
                        ) * 9;

                    elemento.style.transform =
                        `perspective(1200px)
                        rotateX(${rotacionX}deg)
                        rotateY(${rotacionY}deg)
                        translateY(-8px)`;

                    elemento.style.setProperty(
                        "--x",
                        `${(x / rect.width) * 100}%`
                    );

                    elemento.style.setProperty(
                        "--y",
                        `${(y / rect.height) * 100}%`
                    );

                }
            );

            elemento.addEventListener(
                "mouseleave",
                () => {

                    elemento.style.transform =
                        "perspective(1200px) rotateX(0deg) rotateY(0deg) translateY(0)";

                }
            );

        }
    );

}

document.addEventListener(
    "DOMContentLoaded",
    cargarExperiencia
);