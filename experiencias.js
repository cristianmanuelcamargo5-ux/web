function crearGaleria(fotos) {

    return fotos.map(
        foto => `
            <div
                class="foto-experiencia"
                data-foto="${foto}"
            >

                <img
                    src="${foto}"
                    alt="Fotografía de Sáchica"
                >

            </div>
        `
    ).join("");

}

function crearBotonUbicacion(experiencia) {

    if (!experiencia.ubicacion) {
        return "";
    }

    return `
        <a
            href="${experiencia.ubicacion}"
            target="_blank"
            rel="noopener"
            class="boton"
        >
            📍 VER UBICACIÓN
        </a>
    `;

}

